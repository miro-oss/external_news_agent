-- Company-wide preferences are drafts until an explicit optimistic-versioned user decision.
CREATE TABLE news_company_interests (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id NUMBER(19) NOT NULL REFERENCES news_feedback(id) ON DELETE CASCADE,
    topic_id NUMBER(19),
    instruction VARCHAR2(500 CHAR) NOT NULL,
    reason VARCHAR2(500 CHAR) NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    version NUMBER(19) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    activated_at TIMESTAMP,
    CONSTRAINT uq_company_interest_feedback UNIQUE(feedback_id),
    CONSTRAINT ck_company_interest_status CHECK(status IN ('DRAFT','ACTIVE','REVOKED')),
    CONSTRAINT ck_company_interest_active CHECK(status<>'ACTIVE' OR (topic_id IS NOT NULL AND activated_at IS NOT NULL)),
    CONSTRAINT ck_company_interest_version CHECK(version>0)
);
CREATE INDEX ix_company_interest_topic ON news_company_interests(topic_id,status);

-- Recorded with frozen selection, exposed only after successful report completion.
CREATE TABLE news_company_interest_apps (
    report_id NUMBER(19) NOT NULL REFERENCES news_reports(id) ON DELETE CASCADE,
    criterion_id NUMBER(19) NOT NULL REFERENCES news_company_interests(id) ON DELETE CASCADE,
    criterion_version NUMBER(19) NOT NULL,
    topic_id_snapshot NUMBER(19) NOT NULL,
    instruction_snapshot VARCHAR2(500 CHAR) NOT NULL,
    evaluated_count NUMBER(10) NOT NULL,
    suppressed_count NUMBER(10) NOT NULL,
    evaluated_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_company_interest_apps PRIMARY KEY(report_id,criterion_id,criterion_version),
    CONSTRAINT ck_company_interest_counts CHECK(evaluated_count>0 AND suppressed_count>=0 AND suppressed_count<=evaluated_count)
);
CREATE INDEX ix_company_interest_applied ON news_company_interest_apps(criterion_id,criterion_version);

ALTER TABLE news_reports ADD company_selection_recorded_yn CHAR(1) DEFAULT 'N' NOT NULL;
ALTER TABLE news_reports ADD CONSTRAINT ck_report_company_selection CHECK(company_selection_recorded_yn IN ('Y','N'));

-- Existing opinions are editable drafts. Full original comment/diagnosis/topics remain in news_feedback.
-- Multiple event topics require an explicit topic choice; never silently select the first topic.
INSERT INTO news_company_interests(feedback_id,topic_id,instruction,reason,status,version,created_at,updated_at)
SELECT f.id,
    (SELECT CASE WHEN COUNT(DISTINCT t.topic_id)=1 THEN MIN(t.topic_id) ELSE NULL END
     FROM JSON_TABLE(f.input_json,'$.event.topics[*]' COLUMNS(topic_id NUMBER PATH '$.id')) t),
    SUBSTR(TRIM(f.user_comment),1,500),
    '원래 관심 의견을 초안으로 옮겼습니다. 적용할 기준과 주제를 확인해 주세요.',
    'DRAFT',1,COALESCE(f.finished_at,f.created_at),COALESCE(f.finished_at,f.created_at)
FROM news_feedback f
WHERE f.event_key IS NOT NULL AND f.recipient_id IS NULL AND f.status='COMPLETED' AND f.verdict='PREFERENCE'
  AND JSON_EXISTS(f.input_json,'$.event.topics') AND TRIM(f.user_comment) IS NOT NULL
  AND COALESCE(JSON_VALUE(f.review_json,'$.meta.mock'),'false')<>'true'
  AND COALESCE(JSON_VALUE(f.review_json,'$.meta.truncated'),'false')<>'true'
  AND NOT EXISTS(SELECT 1 FROM news_company_interests c WHERE c.feedback_id=f.id);
